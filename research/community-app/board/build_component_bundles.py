"""Build repo artifacts only; no world, publication, browser or network access.

Run with the pinned Python before landing. --check validates existing bundles.
Activation copies the resulting files directly into component.code.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP = HERE.parents[1] / 'kernel-lab/apps/map'
HEADER = '// Generated by research/community-app/board/build_component_bundles.py; edit its inputs, then rebuild.\n'


def bundles():
    source = (HERE / 'board-components.js').read_text(encoding='utf-8')
    marker = 'export default {mount'
    if source.count(marker) != 1:
        raise ValueError('Expected one board component export')
    css = json.dumps((HERE / 'board-theme.css').read_text(encoding='utf-8'))
    yield HERE / 'board-components.bundle.js', HEADER + source.replace(marker, 'export default {css:' + css + ',mount', 1)
    yield MAP / 'map-components.bundle.js', HEADER + '\n'.join(
        (MAP / name).read_text(encoding='utf-8')
        for name in ('geo-worker.js', 'geo-engine.js', 'map-components.js'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in bundles():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('STALE COMPONENT BUNDLE: ' + str(path))
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print('COMPONENT BUNDLES ' + ('CHECKED 2' if args.check else 'BUILT 2'))


if __name__ == '__main__':
    main()
