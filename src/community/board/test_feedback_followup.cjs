// Async handler evidence only: no real browser, model, live posts or windows.
const {path,assert,lab,ctx,P,component,api,part,button,tick,descendants}=require('./component_test_support.cjs');
const host=ctx[Symbol.for('agora.action-feedback.v2')];
function reset(){host.entries.clear();host.scopes.clear();host.listeners.clear()}
let checks=0;function check(label,fn){fn();checks++;console.log('PASS '+label)}
(async()=>{
  const notice=component(path.join(lab,'components/action-notice.js'));
  const board=component(path.join(__dirname,'board-components.bundle.js'));
  const generic=component(path.join(lab,'components/catalogue.js'));
  reset();
  const a=api('action-notice',{node:{component:'action-notice',gestures:[{event:'undo'}]}});
  await a.select({channel:'events',opens:'',thread:''});
  let root=notice.mount(a,{scopeKeys:'channel opens thread'}),feedback=notice.feedback(a),wrapped=notice.wrap(a);
  let token=feedback.begin('Working…');
  check('pending notice paints synchronously before any admission',()=>{assert.match(root.textContent,/Working/);assert.equal(button(root,'Undo'),undefined);assert.equal(a.calls.length,0)});
  feedback.finish(token,{records:['r201']},'Attendance saved.');
  const staleUndo=button(root,'Undo');
  const nav=wrapped.select({channel:'asks',opens:'asks'});
  check('navigation hides the previous view notice synchronously',()=>assert.equal(root.hidden,true));
  await nav;await staleUndo.click();
  check('detached previous-view Undo cannot send its receipt',()=>assert.equal(a.calls.length,0));
  token=feedback.begin('Working…');
  await wrapped.select({channel:'events'});await wrapped.select({channel:'asks'});
  check('late completion is discarded after leaving and returning',()=>{assert.equal(feedback.finish(token,{records:['r202']},'Old response'),false);assert.equal(feedback.get(),null)});
  token=feedback.begin('Working…');feedback.finish(token,{records:['r203']},'First');
  const old=button(root,'Undo');
  token=feedback.begin('Working…');feedback.finish(token,{records:['r204']},'Second');
  await old.click();await button(root,'Undo').click();
  check('replacement invalidates stale button and exact current receipt is used',()=>{assert.equal(a.calls.length,1);assert.equal(a.calls[0].values.value,'r204')});
  token=feedback.begin('Working…');feedback.finish(token,{records:['r205']},'Third');
  const externalOld=button(root,'Undo');
  await a.select({opens:'documents'});await externalOld.click();
  check('external scope change also fails closed before Undo',()=>assert.equal(a.calls.length,1));
  const rejected=feedback.begin('Working…');
  feedback.fail(rejected,Error('permission refused'));
  check('refused action ends pending and gives its real reason',()=>{assert.match(root.textContent,/permission refused/);assert.equal(button(root,'Undo'),undefined)});

  reset();
  const reply=api('board-thread',{children:[{facts:{id:'post1'},children:[]}],draft:{text:'One reply'}});
  await reply.select({thread:'post1',replyTo:'post1'});
  let release;reply.fire=async(event,values)=>{reply.calls.push({event,values});await new Promise(r=>release=r);return {made:['reply1']}};
  root=board.mount(reply,{});
  const posting=root.querySelector('form').event('submit');
  check('reply clears and locks before the admission promise resolves',()=>{assert.equal(part(root,'reply').value,'');assert.equal(part(root,'reply').disabled,true);assert.match(root.textContent,/Posting reply/);assert.equal(button(root,'Post reply').disabled,true)});
  await root.querySelector('form').event('submit');
  check('second reply submit while pending cannot post',()=>assert.equal(reply.calls.length,1));
  release();await posting;
  reset();
  const offer=api('input');root=generic.mount(offer,{commit:'submit',submitLabel:'Post offer'});
  part(root,'control').value='Seedlings';await part(root,'control').event('input');
  offer.fire=async()=>{offer.calls.push('submit');await new Promise(r=>release=r);throw Error('refused fixture')};
  const offering=part(root,'submit').click();
  check('Offer clears locks and reports sending before admission',()=>{assert.equal(part(root,'control').value,'');assert.equal(part(root,'control').disabled,true);assert.match(root.textContent,/Sending/);assert.equal(part(root,'submit').disabled,true)});
  root=generic.mount(offer,{commit:'submit',submitLabel:'Post offer'});
  check('Offer stays empty and locked after a pending repaint',()=>{assert.equal(part(root,'control').value,'');assert.equal(part(root,'control').disabled,true)});
  await part(root,'submit').click();release();await offering;
  check('Offer refusal restores original draft and permits retry',()=>{assert.equal(offer.calls.length,1);assert.equal(part(root,'control').value,'Seedlings');assert.equal(part(root,'control').disabled,false)});

  reset();
  let dialog;P.overlay=(kind,body)=>{dialog=body;return {node:body,close(){}}};
  const kinds=[{name:'lost-pet',fields:'pet_name last_seen'},...['spot','map','map-layer','route','structure'].map(name=>({name,fields:'name',compose_scope:'map'}))];
  const composer=api('board-composer',{read:async line=>line==='rows kind'?kinds:[]});
  await composer.select({compose:'yes'});board.mount(composer,{});await tick();
  check('legacy Lost pet remains available while internal map kinds are excluded',()=>assert.deepEqual(descendants(dialog).filter(n=>n.dataset.postType).map(n=>n.dataset.postType),['lost-pet']));
  const shell=api('board-search',{read:async line=>line==='rows kind'?kinds:[]});await shell.select({search:'pet'});
  root=board.mount(shell,{});await tick();
  check('search Type hides internal kinds but offers Lost pet',()=>{assert.match(root.textContent,/Lost pet/i);for(const word of ['Map-layer','Structure','Route','Spot'])assert.doesNotMatch(root.textContent,new RegExp(word))});
  const limited=api('board-catchup',{children:[{facts:{id:'post'}}],read:async line=>{if(line==='model.status')throw Error('daily local model limit reached; please try tomorrow or ask a steward');return []}});
  root=board.mount(limited,{});await tick();
  check('summary displays daily limit verbatim without calling a model',()=>{assert.match(root.textContent,/daily local model limit reached/);assert.doesNotMatch(root.textContent,/not answering/);assert.equal(limited.calls.length,0)});
  const docs=component(path.join(__dirname,'document-components.bundle.js'));
  const library=api('document-library');await library.select({opens:'documents'});
  check('embedded Documents omits its duplicated heading',()=>assert.equal(part(docs.mount(library,{}),'heading'),undefined));
  await library.select({opens:''});
  check('standalone Documents retains its own heading',()=>assert.ok(part(docs.mount(library,{}),'heading')));
  const document=api('document-entry',{facts:{id:'file1',kind:'document-link',name:'Agenda',source_post:'post1',source_text:'Bring the draft agenda to our meeting',library:'library'}});
  check('document provenance uses real untitled post words',()=>assert.match(part(docs.mount(document,{}),'source').textContent,/From post: Bring the draft agenda to our meeting/));

  reset();
  const work=component(path.join(lab,'components/work-line.js'));
  const w=api('work-line',{node:{component:'work-line',gestures:[{event:'done'}]}});
  const wn=api('action-notice',{node:{component:'action-notice',gestures:[{event:'undo'}]},view:w.view,select:w.select});
  const outcome=notice.mount(wn,{stateKey:'workNotice',scopeKeys:'workFilter workPage'});
  w.fire=async()=>{await new Promise(r=>release=r);return {records:['r301']}};
  const wr=work.mount(w,{title:'Fixture work',state:'Active'}),finishing=button(wr,'Mark done').click();
  check('Work action really displays pending immediately in shared notice',()=>{assert.equal(outcome.hidden,false);assert.match(outcome.textContent,/Working/);assert.equal(button(outcome,'Undo'),undefined)});
  release();await finishing;await button(outcome,'Undo').click();
  check('Work completion has real receipt recovery through authored gesture',()=>assert.equal(wn.calls[0].values.value,'r301'));
  console.log('FEEDBACK FOLLOWUP CHECKS '+checks);
})().catch(e=>{console.error(e);process.exitCode=1});
