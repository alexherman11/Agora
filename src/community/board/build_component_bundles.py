"""Build repo artifacts only; no world, publication, browser or network access.

Run with the pinned Python before landing. --check validates existing bundles.
Activation copies the resulting files directly into component.code.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP = HERE.parents[1] / 'agora/apps/map'
COMPONENTS = HERE.parents[1] / 'agora/components'
START = '// BEGIN SHARED ACTION FEEDBACK\n'
END = '// END SHARED ACTION FEEDBACK\n'
HEADER = '// Generated by src/community/board/build_component_bundles.py; edit its inputs, then rebuild.\n'


def bundles():
    shared = START + (COMPONENTS / 'action-feedback.js').read_text(encoding='utf-8') + '\n' + END
    for name in ('action-notice', 'catalogue', 'slots', 'calendar', 'work-overview', 'work-line'):
        path = COMPONENTS / (name + '.js')
        source = path.read_text(encoding='utf-8')
        if source.startswith(START):
            source = source.split(END, 1)[1]
        yield path, shared + source
    source = (HERE / 'board-components.js').read_text(encoding='utf-8')
    marker = 'export default {mount'
    if source.count(marker) != 1:
        raise ValueError('Expected one board component export')
    css = json.dumps((HERE / 'board-theme.css').read_text(encoding='utf-8'))
    yield HERE / 'board-components.bundle.js', HEADER + shared + source.replace(marker, 'export default {css:' + css + ',mount', 1)
    yield MAP / 'map-components.bundle.js', HEADER + shared + '\n'.join(
        (MAP / name).read_text(encoding='utf-8')
        for name in ('geo-worker.js', 'geo-engine.js', 'map-components.js'))
    source = (HERE / 'document-components.js').read_text(encoding='utf-8')
    css = json.dumps((HERE / 'documents.css').read_text(encoding='utf-8'))
    yield HERE / 'document-components.bundle.js', HEADER + shared + source.replace(marker, 'export default {css:' + css + ',mount', 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in bundles():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('STALE COMPONENT BUNDLE: ' + str(path))
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print('COMPONENT BUNDLES ' + ('CHECKED 9' if args.check else 'BUILT 9'))


if __name__ == '__main__':
    main()
